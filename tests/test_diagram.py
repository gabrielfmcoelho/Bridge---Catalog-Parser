from __future__ import annotations

from conftest import base, external, write

from catalog_parser import generate_diagram, lint_file, render_mermaid
from catalog_parser.cli import diagram_main


def _catalog(path):
    return lint_file(path).catalog


def test_nodes_edges_and_direction(tmp_path, pair):
    a, b = pair
    fa, fb = write(tmp_path, a), write(tmp_path, b)
    text = render_mermaid(_catalog(fb), [_catalog(fa)])
    assert text.startswith("flowchart LR")
    assert 'subgraph ci_svc_b["svc-b"]' in text and 'subgraph ci_svc_a["svc-a"]' in text
    # consumer --> provider, labelled with the PROVIDER's protocol/port (known through the peer)
    assert 'svc_b_client -->|"http:8000"| svc_a_api' in text
    assert 'svc_a_api["api<br/>rest-api · http:8000"]' in text


def test_without_peers_the_label_is_unknown_but_the_edge_stays(tmp_path, pair):
    _, b = pair
    text = render_mermaid(_catalog(write(tmp_path, b)))
    assert 'svc_a_api["api"]' in text
    assert "svc_b_client --> svc_a_api" in text


def test_downstream_edge_points_at_the_local_component(tmp_path, pair):
    a, b = pair
    text = render_mermaid(_catalog(write(tmp_path, a)), [_catalog(write(tmp_path, b))])
    assert 'svc_b_client -->|"http:8000"| svc_a_api' in text


def test_external_and_consumer_without_catalog(tmp_path):
    d = base("svc-a")
    d["dependencies"]["upstream"] = [external(via="svc-z")]
    d["dependencies"]["downstream"] = [{"ci": "dashboard", "local_component": "api"}]
    text = render_mermaid(_catalog(write(tmp_path, d)))
    assert 'ext_oracle_x(["oracle-x<br/>oracle · tcp:1521"])' in text
    assert 'ci_svc_a -->|"tcp:1521 · via svc-z"| ext_oracle_x' in text
    assert 'ext_dashboard(["dashboard"])' in text and 'ext_dashboard -->|"http:8000"| svc_a_api' in text
    assert "classDef medium" in text and "class svc_a_api high" in text


def test_data_components_are_cylinders(tmp_path):
    d = base("svc-a")
    d["components"].append({"name": "gold", "category": "data", "technology": "iceberg",
                            "criticality": "medium", "description": "tables"})
    assert 'svc_a_gold[("gold<br/>iceberg")]' in render_mermaid(_catalog(write(tmp_path, d)))


def test_output_is_deterministic(tmp_path, pair):
    _, b = pair
    (write(tmp_path, b).parents[1] / "docs").mkdir()
    first = generate_diagram(tmp_path / "svc-b").path.read_text()
    second = generate_diagram(tmp_path / "svc-b").path.read_text()
    assert first == second and "Generated by catalog-parser" in first and "```mermaid" in first


def test_writes_into_docs(tmp_path, pair):
    _, b = pair
    (write(tmp_path, b).parents[1] / "docs").mkdir()
    result = generate_diagram(tmp_path / "svc-b")
    assert result.path == tmp_path / "svc-b" / "docs" / "catalog" / "dependencies.md" and result.path.exists()
    assert result.issues == []


def test_files_go_into_docs_catalog_and_never_loose_in_docs(tmp_path, pair):
    _, b = pair
    docs = write(tmp_path, b).parents[1] / "docs"
    docs.mkdir()
    generate_diagram(tmp_path / "svc-b")
    assert [p.name for p in docs.iterdir()] == ["catalog"]
    assert [p.name for p in (docs / "catalog").iterdir()] == ["dependencies.md"]


def test_subdir_and_filename_are_configurable(tmp_path, pair):
    _, b = pair
    (write(tmp_path, b).parents[1] / "docs").mkdir()
    assert diagram_main([str(tmp_path / "svc-b"), "--subdir", "map/deps", "--filename", "d.md"]) == 0
    assert (tmp_path / "svc-b" / "docs" / "map" / "deps" / "d.md").exists()


def test_missing_docs_folder_warns_and_does_not_fail(tmp_path, pair, capsys):
    _, b = pair
    write(tmp_path, b)
    result = generate_diagram(tmp_path / "svc-b")
    assert result.path is None and result.markdown
    assert [(i.code, i.severity) for i in result.issues] == [("W301", "warning")]
    assert not (tmp_path / "svc-b" / "docs").exists()      # neither docs/ nor docs/catalog/ is created
    assert diagram_main([str(tmp_path / "svc-b")]) == 0     # warning only
    assert "W301" in capsys.readouterr().err


def test_invalid_catalog_cannot_be_drawn(tmp_path, pair, capsys):
    _, b = pair
    b["components"][0]["criticality"] = "urgent"
    write(tmp_path, b)
    result = generate_diagram(tmp_path / "svc-b")
    assert result.markdown is None and result.issues[0].code == "E002"
    assert diagram_main([str(tmp_path / "svc-b")]) == 1


def test_cli_writes_file_and_accepts_repeatable_peers(tmp_path, pair, capsys):
    a, b = pair
    write(tmp_path, a)
    (write(tmp_path, b).parents[1] / "docs").mkdir()
    assert diagram_main([str(tmp_path / "svc-b"), "--peers", str(tmp_path / "svc-a"), "--peers", str(tmp_path)]) == 0
    assert "wrote" in capsys.readouterr().out
    assert 'http:8000"| svc_a_api' in (tmp_path / "svc-b" / "docs" / "catalog" / "dependencies.md").read_text()


def test_cli_stdout_does_not_need_docs(tmp_path, pair, capsys):
    _, b = pair
    write(tmp_path, b)
    assert diagram_main([str(tmp_path / "svc-b"), "--stdout"]) == 0
    assert "flowchart LR" in capsys.readouterr().out


def test_cli_missing_path_is_a_usage_error(tmp_path):
    assert diagram_main([str(tmp_path / "nope")]) == 2
